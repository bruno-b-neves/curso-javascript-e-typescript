const nome = prompt("Digite seu nome completo:");
document.body.innerHTML += `O meu nome é: ${nome}.<br/>`;
document.body.innerHTML += `Meu nome tem ${nome.length} letras.<br/>`;
document.body.innerHTML += `A segunda letra do meu nome é: ${nome[1]}.<br />`;
document.body.innerHTML += `Qual o primeiro índice da letra "o" do meu nome?  ${nome.indexOf("o")}. <br />`;
document.body.innerHTML += `Qual o último índice da letra "o" do meu nome? ${nome.lastIndexOf("o")} <br />`;
document.body.innerHTML += `As últimas 3 letras do meu nome são: ${nome.slice(16, 19)}. <br />`;
document.body.innerHTML += `As palavras do meu nome são: ${nome.split("").join(" ")}. <br />`;
document.body.innerHTML += `Meu nome com letras maiúsculas: ${nome.toUpperCase()}. <br />`;
document.body.innerHTML += `Meu nome com letras minúsculas: ${nome.toLowerCase()}`;
